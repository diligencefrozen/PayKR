// Generate crawlable Pages entries from the same dictionaries and owned catalog used at runtime.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { locales, localizedPagePath } from '../src/i18n/registry.js';
import { shellMarkup } from './shell-markup.mjs';
import { buildSeoHead, directoryPages, resourceLinks } from './seo.mjs';
import { categoryIcon } from '../src/views/category-icons.js';
const base = 'https://diligencefrozen.github.io/PayKR/';
const languages = Object.keys(locales);
const pages = { index: 'map', online: 'online', guide: 'guide' };
const rows = JSON.parse(await readFile(new URL('../src/data/online.json', import.meta.url)));
const escape = (s) =>
  String(s)
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
const file = (name, lang) => name + (lang === 'en' ? '' : '.' + lang) + '.html';
const canonical = (name, lang) => base + (name === 'index' && lang === 'en' ? '' : file(name, lang));
async function output(path, content) {
  const url = new URL('../' + path, import.meta.url);
  if (process.argv.includes('--check')) {
    if ((await readFile(url, 'utf8')).replaceAll('\r\n', '\n') !== content) throw Error('Regenerate ' + path);
  } else await writeFile(url, content);
}
const sitemap = [];
const revision = createHash('sha256');
for (const path of ['online.json', 'stores.json', 'evidence.js']) {
  const source = await readFile(new URL('../src/data/' + path, import.meta.url), 'utf8');
  revision.update(source.replaceAll('\r\n', '\n'));
}
await output(
  'src/data/catalog-version.js',
  '// Generated by scripts/pages.mjs from the owned catalog and payment evidence.\nexport const VERSION = ' +
    JSON.stringify(revision.digest('hex').slice(0, 16)) +
    ';\n',
);
for (const [name, type] of Object.entries(pages)) {
  const template = (
    await readFile(new URL('../templates/' + name + '.html', import.meta.url), 'utf8')
  ).replaceAll('\r\n', '\n');
  const { header, footer } = shellMarkup(type);
  const alternates = languages
    .map((l) => [l, canonical(name, l)])
    .concat([['x-default', canonical(name, 'en')]]);
  for (const lang of languages) {
    const dict = (await locales[lang].load()).default;
    const trans = (k) => {
      if (!dict[k]) throw Error('Missing ' + k);
      return escape(dict[k]);
    };
    const heading = '<header data-header>' + header + '</header>';
    let html = template
      .replace(/<header data-header>[\s\S]*?<\/header>/, heading)
      .replace(/<footer data-footer>[\s\S]*?<\/footer>/, '<footer data-footer>' + footer + '</footer>');
    html = html.replace(/<a\b[^>]*\bdata-page="([^"]+)"[^>]*>/g, (tag, path) =>
      tag.replace(/\bhref="[^"]+"/, 'href="' + localizedPagePath(path, lang) + '"'));
    html = html
      .replace(
        /<html[^>]*>/,
        '<html lang="' +
          lang +
          '" dir="' + locales[lang].dir + '"' +
          (' data-entry-locale="' + lang + '"') +
          '>',
      )
      .replace(/  <link rel="(?:canonical|alternate)"[^>]+>\n/g, '')
      .replace(
        '</head>',
        '  <link rel="canonical" href="' +
          canonical(name, lang) +
          '">\n' +
          alternates
            .map(([l, url]) => '  <link rel="alternate" hreflang="' + l + '" href="' + url + '">')
            .join('\n') +
          '\n</head>',
      );
    // Only literal template bindings are interpolated. External place data never enters this generator.
    html = html.replace(
      /<([\w-]+)\b([^>]*?\bdata-i18n="([^"]+)"[^>]*)>[^<]*<\/\1>/g,
      (_, tag, attrs, key) => '<' + tag + attrs + '>' + trans(key) + '</' + tag + '>',
    );
    html = html.replace(
      /<[\w-]+\b[^>]*\bdata-i18n-(?:content|placeholder|aria-label|title)="[^"]+"[^>]*>/g,
      (tag) => {
        for (const [, attr, key] of [
          ...tag.matchAll(/data-i18n-(content|placeholder|aria-label|title)="([^"]+)"/g),
        ]) {
          const re = new RegExp(' ' + attr + '="[^"]*"');
          if (re.test(tag)) tag = tag.replace(re, ' ' + attr + '="' + trans(key) + '"');
          else tag = tag.replace(/>$/, ' ' + attr + '="' + trans(key) + '">');
        }
        return tag;
      },
    );
    html = html.replace(
      /<select data-locale([^>]*)><\/select>/g,
      '<select data-locale$1>' +
        languages
          .map(
            (l) =>
              '<option value="' +
              l +
              '"' +
              (l === lang ? ' selected' : '') +
              '>' +
              escape(locales[l].short || locales[l].name) +
              '</option>',
          )
          .join('') +
        '</select>',
    );
    if (type === 'online') {
      const cards = rows.map(
        (row) =>
          '<article class="brand"><div class="brand-logo"><img loading="lazy" src="' +
          escape(row.icon) +
          '" alt="" width="120" height="64"></div><div class="brand-info"><span class="brand-name">' +
          escape(row.names[lang] || row.names.en || row.names.ko) +
          '</span><span class="brand-category">' +
          trans(row.label) +
          '</span></div><details><summary class="badge brand_listed">' +
          trans('ecommerce.paymentBadge') +
          '</summary><p>' +
          trans('place.channelOnline') +
          '</p></details></article>',
      );
      html = html
        .replace('<div id="first-cards"></div>', '<div id="first-cards">'+cards.slice(0,8).join('\n')+'</div>')
        .replace('<div id="other-cards"></div>', '<div id="other-cards">'+cards.slice(8).join('\n')+'</div>')
        .replace(
          'id="totalCount" role="status"></p>',
          'id="totalCount" role="status">' +
            trans('ecommerce.count').replace('{count}', String(rows.length)) +
            '</p>',
        )
        .replace(
          '<div class="nav-control-categories" id="directory-filters"></div>',
          '<div class="nav-control-categories" id="directory-filters">' +
            Object.entries({all: 'grid', shopping: 'bag', food: 'food', travel: 'bed', convenience: 'store', other: 'more'})
              .map(([key, icon]) => `<button type="button" data-category="${key}" aria-pressed="${key === 'all'}">${categoryIcon(icon)}<span data-i18n="filter.${key}">${trans('filter.' + key)}</span></button>`)
              .join('') +
            '</div>',
        );
    }
    html = html.replace('</head>', buildSeoHead({name, lang, url: canonical(name, lang), dict}) + '\n</head>');
    html = html.replace('<!-- SEO_RESOURCES -->', resourceLinks(lang, name));
    await output(file(name, lang), html.trimEnd() + '\n');
    sitemap.push(
      '  <url><loc>' +
        canonical(name, lang) +
        '</loc>\n' +
        alternates
          .map(([l, url]) => '    <xhtml:link rel="alternate" hreflang="' + l + '" href="' + url + '"/>')
          .join('\n') +
        '\n  </url>',
    );
  }
}
for (const page of await directoryPages()) {
  await output(page.file, page.html);
  sitemap.push(page.sitemap);
}
sitemap.push('  <url><loc>' + base + 'terms.html</loc></url>');
await output(
  'sitemap.xml',
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' +
    sitemap.join('\n') +
    '\n</urlset>\n',
);
console.log(languages.length * Object.keys(pages).length + ' localized app entries, 2 brand directories, terms and sitemap verified');
