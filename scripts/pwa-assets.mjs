// Run after editing an offline asset. --check is a read-only CI freshness check.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const digest = (contents) => createHash('sha256').update(contents).digest('base64');
const pages = (await readdir(root)).filter((file) =>
  /^(?:(?:index|online|guide)(?:\.(?:[a-z]{2}|zh-Hans|zh-Hant))?|brands(?:\.ko)?|offline|terms)\.html$/.test(file),
);
const files = [
  ...pages,
  'docs/release-history.txt',
  'manifest.webmanifest',
  'favicon.svg',
  'place-text.js',
  'vendor/koroman/koroman.browser.js',
];
for (const page of pages) {
  const html = await readFile(join(root, page), 'utf8');
  for (const tag of html.matchAll(
    /(?:src|href)=["'](?:\.\/)?([\w./-]+\.(?:css|js|mjs))(?:\?[^"']*)?["']/gi,
  )) {
    if (
      tag[1].startsWith('src/') ||
      [
        'extensions.css', 'shared.css',
        'main.css',
        'online.css', 'seo.css',
        'theme.js',
        'place-text.js',
        'vendor/koroman/koroman.browser.js',
      ].includes(tag[1])
    )
      files.push(tag[1]);
  }
}
const allowedTypes = /\.(?:js|mjs|css|json|png|svg|webp)$/i;
async function collect(directory) {
  for (const entry of await readdir(join(root, directory), { withFileTypes: true })) {
    const path = directory + '/' + entry.name;
    if (entry.isDirectory()) await collect(path);
    else if (entry.isFile() && allowedTypes.test(path)) files.push(path);
  }
}
for (const directory of ['src', 'icons', 'logo_online']) await collect(directory);
const references = (
  await Promise.all(
    files
      .filter((file) => /\.(?:html|css|js|mjs|json)$/.test(file))
      .map((file) => readFile(join(root, file), 'utf8')),
  )
).join('\n');
for (const entry of await readdir(join(root, 'logo'))) {
  if (references.includes('logo/' + entry)) files.push('logo/' + entry);
}
const assets = [];
for (const file of [...new Set(files)].sort()) {
  const bytes = await readFile(join(root, file));
  const hashes = new Set();
  if (/\.(?:txt|html|webmanifest|svg|css|js|mjs|json)$/i.test(file)) {
    // Git can check out LF or CRLF. Both encodings represent the same release.
    const lf = bytes.toString('utf8').replaceAll('\r\n', '\n');
    hashes.add(digest(lf));
    hashes.add(digest(lf.replaceAll('\n', '\r\n')));
  }
  hashes.add(digest(bytes));
  assets.push([file, [...hashes].map((hash) => 'sha256-' + hash).join(' ')]);
}
const release = createHash('sha256').update(JSON.stringify(assets)).digest('hex').slice(0, 16);
const output =
  '// Generated by node scripts/pwa-assets.mjs\n' +
  'self.PAYKR_RELEASE = ' +
  JSON.stringify(release) +
  ';\n' +
  'self.PAYKR_SHELL = ' +
  JSON.stringify(assets, null, 1) +
  ';\n';
const target = join(root, 'pwa-assets.js');
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== output) {
    throw new Error('Refresh offline asset revisions with node scripts/pwa-assets.mjs');
  }
} else {
  await writeFile(target, output);
}
console.log(assets.length + ' offline assets, revision ' + release);
